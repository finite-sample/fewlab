"""Generate every table, figure, and inline number the manuscript uses.

Nothing computed reaches the page by hand. Tables are written as booktabs
fragments the document `\\input`s, the figure is written as a PDF, and every
number quoted in prose is emitted as a `\\newcommand` so a sentence and a table
cannot drift apart. Re-running this script after any change to the data or the
estimator updates all three at once.

    python benchmarks/make_exhibits.py --data benchmarks/data --out ms/generated
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

import numpy as np
import pandas as pd
from run_yg_benchmark import MEASURES, frontier, load, run, truth
from style import DESIGN_ORDER, DESIGN_STYLE, use_style
from synthetic import covariate_experiment, loss_divergence

import fewlab

BUDGETS = [100, 250, 500, 1000, 2000]
SHOWN_BUDGETS = [250, 1000, 2000]
FRONTIER_BUDGETS = [250, 1000, 4000]
CUBE_REPS = 500


def fmt(value: float, digits: int = 3) -> str:
    """Format a number to a fixed count of significant digits.

    Args:
        value: The number.
        digits: Significant digits to keep.

    Returns:
        A string with thousands separators for large integers.
    """
    if value >= 1000 and float(value).is_integer():
        return f"{int(value):,}"
    return f"{float(f'%.{digits}g' % value):g}"


def diagnostics(study, labels, B, budget: int, reps: int) -> dict:
    """Measure why intervals from a poor design fail to cover.

    The variance estimator is unbiased under every design here, so a coverage
    shortfall has to come from somewhere else. This computes the two candidates:
    the skewness of the estimator, which breaks the normal approximation, and
    the relative dispersion of the variance estimate itself, which makes any one
    interval unreliable even when the estimator averages correctly.

    Args:
        study: The study.
        labels: True labels.
        B: The finite-population truth.
        budget: Labeling budget.
        reps: Replicates.

    Returns:
        Per-design skew, variance-estimator ratio and dispersion, and the
        conservatism of the Poisson variance under a fixed-size draw.
    """
    out = {}
    for name in ("pps", "srs"):
        design = study.design(budget, method=name)
        rng = np.random.default_rng(99)
        est, var = [], []
        for _ in range(reps):
            s = study.draw(design, random_state=rng, fixed_size=False)
            if len(s) == 0:
                continue
            e = fewlab.estimate(study.influence, s, labels.loc[s.items])
            est.append(e.coefficients.to_numpy().ravel())
            var.append(e.design_se.to_numpy().ravel() ** 2)
        est, var = np.array(est), np.array(var)
        out[name] = {
            "skew": float(np.abs(pd.DataFrame(est).skew()).max()),
            "var_ratio": float(np.median(var.mean(0) / est.var(0))),
            "var_dispersion": float(np.median(var.std(0) / var.mean(0))),
        }

    design = study.design(budget)
    rng = np.random.default_rng(101)
    vals, ses = [], []
    # Cube draws cost about a second each at this scale, so this is the
    # expensive part. It still needs enough replicates that a ratio of standard
    # deviations is estimable: at 75 draws its own sampling error is about eight
    # percent, which is larger than the effect being measured.
    for _ in range(CUBE_REPS):
        s = study.draw(design, random_state=rng, fixed_size=True)
        e = fewlab.estimate(study.influence, s, labels.loc[s.items])
        vals.append(e.coefficients.to_numpy().ravel())
        ses.append(e.design_se.to_numpy().ravel())
    vals, ses = np.array(vals), np.array(ses)
    # Pool across coefficients rather than reporting the extremes of 26 separate
    # noisy ratios, whose min and max are dominated by estimation error.
    pooled = float(np.sqrt(np.mean(ses**2) / np.mean(vals.var(axis=0))))
    per_coef = np.asarray(ses).mean(0) / np.asarray(vals).std(0)
    covered = np.abs(vals - B.ravel()) <= 1.96 * ses
    out["cube"] = {
        "se_ratio": pooled,
        "se_ratio_median": float(np.median(per_coef)),
        "coverage": float(covered.mean()),
        "reps": CUBE_REPS,
    }
    return out


def write_evidence_table(table: pd.DataFrame, path: Path) -> None:
    """Write the design-comparison table body.

    Args:
        table: Benchmark results.
        path: Output file.
    """
    lines = [
        r"% Generated by benchmarks/make_exhibits.py. Do not edit.",
        r"\begin{tabular}{rlrrrrr}",
        r"\toprule",
        r"$K$ & Design & RMSE & RMSE/SRS & Bias & Coverage & Core \\",
        r"\midrule",
    ]
    for k, budget in enumerate(SHOWN_BUDGETS):
        if k:
            lines.append(r"\midrule")
        block = table[table.budget == budget]
        for name in DESIGN_ORDER:
            r = block[block.design == name].iloc[0]
            lines.append(
                f"{budget:,} & {DESIGN_STYLE[name]['label']} & "
                f"{fmt(r.rmse)} & {r.rmse_vs_srs:.3f} & "
                f"{fmt(r.bias_norm, 2)} & {r.coverage:.3f} & "
                f"{int(r.certainty_core):,} \\\\"
            )
    lines += [r"\bottomrule", r"\end{tabular}"]
    path.write_text("\n".join(lines) + "\n")


def write_frontier_table(curve: pd.DataFrame, path: Path) -> None:
    """Write the shrinkage-frontier table body, marking each block's minimum.

    Args:
        curve: Frontier results.
        path: Output file.
    """
    lines = [
        r"% Generated by benchmarks/make_exhibits.py. Do not edit.",
        r"\begin{tabular}{rrrrr}",
        r"\toprule",
        r"$K$ & $\alpha$ & Bias & SD & RMSE \\",
        r"\midrule",
    ]
    for k, budget in enumerate(FRONTIER_BUDGETS):
        if k:
            lines.append(r"\midrule")
        block = curve[curve.budget == budget]
        best = block.rmse.idxmin()
        for idx, r in block.iterrows():
            rmse = fmt(r.rmse)
            cell = f"\\textbf{{{rmse}}}" if idx == best else rmse
            lines.append(
                f"{budget:,} & {r.alpha:.2f} & {fmt(r.bias)} & "
                f"{fmt(r.sd)} & {cell} \\\\"
            )
    lines += [r"\bottomrule", r"\end{tabular}"]
    path.write_text("\n".join(lines) + "\n")


def write_figure(table: pd.DataFrame, norm: float, path: Path) -> None:
    """Draw accuracy and interval validity against the labeling budget.

    Two panels because there are two questions. The left asks how close the
    estimate gets, against the size of the quantity being estimated. The right
    asks whether the interval around it can be believed. Series are labelled
    directly rather than through a legend.

    Args:
        table: Benchmark results.
        norm: Frobenius norm of the truth, drawn as a reference line.
        path: Output PDF.
    """
    use_style()
    import matplotlib.pyplot as plt

    fig, (ax_err, ax_cov) = plt.subplots(1, 2, figsize=(6.9, 3.0))
    for name in DESIGN_ORDER:
        d = table[table.design == name].sort_values("budget")
        st = DESIGN_STYLE[name]
        ax_err.plot(d.budget, d.rmse, marker=st["marker"], color=st["color"])
        ax_cov.plot(d.budget, d.coverage, marker=st["marker"], color=st["color"])
        ax_err.annotate(
            st["label"],
            (d.budget.iloc[-1], d.rmse.iloc[-1]),
            xytext=(4, 0),
            textcoords="offset points",
            color=st["color"],
            fontsize=7,
            va="center",
        )

    ax_err.axhline(norm, ls=":", c="black", lw=0.8)
    ax_err.annotate(
        "size of $\\beta^*$ itself",
        (table.budget.min(), norm),
        xytext=(2, 4),
        textcoords="offset points",
        fontsize=7,
    )
    ax_err.set(
        xscale="log",
        yscale="log",
        xlabel="Domains labeled",
        ylabel="Error in $\\widehat\\beta$ (Frobenius norm)",
        title="Accuracy",
        xlim=(80, 6200),
    )
    ax_cov.axhline(0.95, ls=":", c="black", lw=0.8)
    ax_cov.annotate(
        "nominal 0.95",
        (table.budget.min(), 0.95),
        xytext=(2, 4),
        textcoords="offset points",
        fontsize=7,
    )
    ax_cov.set(
        xscale="log",
        xlabel="Domains labeled",
        ylabel="Coverage of the 95\\% interval",
        title="Interval validity",
        ylim=(0.80, 1.0),
    )
    fig.tight_layout()
    fig.savefig(path)
    plt.close(fig)


def main() -> None:
    """Compute everything and write the generated directory."""
    ap = argparse.ArgumentParser()
    ap.add_argument("--data", type=Path, default=Path("benchmarks/data"))
    ap.add_argument("--out", type=Path, default=Path("ms/generated"))
    ap.add_argument("--reps", type=int, default=300)
    args = ap.parse_args()
    args.out.mkdir(parents=True, exist_ok=True)

    study, labels = load(args.data)
    B = truth(study, labels)
    stats = json.loads((args.data / "stats.json").read_text())

    rows = []
    for budget in BUDGETS:
        rows.extend(run(study, labels, B, budget, args.reps, seed=20250820 + budget))
    table = pd.DataFrame(rows)
    table["rmse_vs_srs"] = table.groupby("budget")["rmse"].transform(
        lambda s: s / s[table.loc[s.index, "design"] == "srs"].iloc[0]
    )
    curve = frontier(study, labels, B, FRONTIER_BUDGETS, reps=min(args.reps, 200))
    diag = diagnostics(study, labels, B, 250, args.reps * 4)

    table.to_csv(args.out / "benchmark.csv", index=False)
    curve.to_csv(args.out / "frontier.csv", index=False)
    write_evidence_table(table, args.out / "tab_evidence.tex")
    write_frontier_table(curve, args.out / "tab_frontier.tex")

    norm = float(np.linalg.norm(B))
    write_figure(table, norm, args.out / "fig_efficiency.pdf")

    pps = table[table.design == "pps"]
    oracle = table[(table.design == "pps_oracle_norms") & (table.budget == 250)]
    oracle_factor = pps[pps.budget == 250].rmse.iloc[0] / oracle.rmse.iloc[0]
    rmse_two_thousand = pps[pps.budget == 2000].rmse.iloc[0]
    norms = (labels**2).sum(axis=1)
    gain = {
        b: 1
        - curve[curve.budget == b].rmse.min() ** 2
        / curve[(curve.budget == b) & (curve.alpha == 1.0)].rmse.iloc[0] ** 2
        for b in FRONTIER_BUDGETS
    }
    zero = {
        b: curve[(curve.budget == b) & (curve.alpha == 0.0)].bias.iloc[0] / norm
        for b in FRONTIER_BUDGETS
    }

    macros = {
        "PanelUsers": f"{stats['panel_users']:,}",
        "PanelDomains": f"{stats['panel_domains']:,}",
        "PanelVisits": f"{stats['panel_visits']:,}",
        "LabeledDomains": f"{stats['labeled_domains']:,}",
        "LabelCoverage": f"{100 * stats['label_coverage_domains']:.1f}",
        "LabeledVisitShare": f"{100 * stats['labeled_visit_share']:.1f}",
        "EvalUsers": f"{stats['eval_users']:,}",
        "EvalDensity": f"{100 * stats['density']:.2f}",
        "TruthNorm": fmt(norm),
        "NumClasses": str(len(MEASURES)),
        "NumCoefficients": str(B.size),
        "BetaRows": str(B.shape[0]),
        "BetaCols": str(B.shape[1]),
        "EffAtTwoFifty": f"{pps[pps.budget == 250].rmse_vs_srs.iloc[0]:.3f}",
        "EffFactorAtTwoFifty": f"{1 / pps[pps.budget == 250].rmse_vs_srs.iloc[0]:.0f}",
        "EffRatioLo": f"{pps.rmse_vs_srs.min():.3f}",
        "EffRatioHi": f"{pps.rmse_vs_srs.max():.3f}",
        "RmseAtTwoThousand": fmt(rmse_two_thousand),
        "RelErrAtTwoThousand": f"{100 * rmse_two_thousand / norm:.0f}",
        "SrsCoverageLo": f"{table[table.design == 'srs'].coverage.min():.2f}",
        "SrsCoverageHi": f"{table[table.design == 'srs'].coverage.max():.2f}",
        "PpsCoverageLo": f"{pps.coverage.min():.3f}",
        "PpsCoverageHi": f"{pps.coverage.max():.3f}",
        "SrsSkew": f"{diag['srs']['skew']:.1f}",
        "PpsSkew": f"{diag['pps']['skew']:.1f}",
        "SrsVarDispersion": f"{diag['srs']['var_dispersion']:.1f}",
        "PpsVarDispersion": f"{diag['pps']['var_dispersion']:.1f}",
        "SrsVarRatio": f"{diag['srs']['var_ratio']:.2f}",
        "PpsVarRatio": f"{diag['pps']['var_ratio']:.2f}",
        "CubeSeExcess": f"{100 * (diag['cube']['se_ratio'] - 1):.0f}",
        "CubeReps": str(diag["cube"]["reps"]),
        "CubeCoverage": f"{diag['cube']['coverage']:.2f}",
        "NormMedian": fmt(float(norms.median()), 2),
        "NormMax": f"{int(norms.max()):,}",
        "OracleFactor": f"{oracle_factor:.1f}",
        "ShrinkGainSmall": f"{100 * gain[250]:.0f}",
        "ShrinkGainMid": f"{100 * gain[1000]:.0f}",
        "ShrinkGainLarge": f"{100 * gain[4000]:.0f}",
        "ZeroFillBiasLo": f"{100 * min(zero.values()):.0f}",
        "ZeroFillBiasHi": f"{100 * max(zero.values()):.0f}",
        "Reps": str(args.reps),
        "FrontierReps": str(min(args.reps, 200)),
        "HeadlineBudget": "250",
        "BudgetShareAtTwoThousand": f"{100 * 2000 / stats['labeled_domains']:.0f}",
        # Reproducing the published coefficients needs the full panel, including
        # the domains whose scan failed, which the hashed extract deliberately
        # does not contain. Source: scripts/implications/config.py in the
        # Blacklight repository, TABLE5_BENCHMARKS and GATE_TOLERANCE.
        "ReproMaxDiff": "0.004",
        "ReproTolerance": "0.02",
    }
    macros.update(covariate_experiment(reps=min(args.reps, 300)))
    macros.update(loss_divergence())
    (args.out / "macros.tex").write_text(
        "% Generated by benchmarks/make_exhibits.py. Do not edit.\n"
        + "".join(f"\\newcommand{{\\{k}}}{{{v}}}\n" for k, v in macros.items())
    )
    print(json.dumps(macros, indent=2))


if __name__ == "__main__":
    main()
